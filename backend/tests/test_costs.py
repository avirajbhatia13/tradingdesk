# the expiry trap
# ---------------------------------------------------------------------------

def test_exercise_stt_is_charged_on_intrinsic_not_premium():
    """A 200-point ITM call on one lot: 200 x 75 x 0.0015 = 22.50, regardless
    of the premium paid for it."""
    assert exercise_stt(200.0, LOT, NOW_2026) == pytest.approx(22.50)


def _square_off_vs_expire(day: date) -> tuple[float, float]:
    """STT on the two ways out of a deep ITM long call.

    200 points of intrinsic, 202 of premium — two points of time value, which
    is realistic for a deep ITM contract near expiry.
    """
    square_off = CostModel().charge([Fill("SELL", 202.0, LOT)], day).stt
    expire = exercise_stt(200.0, LOT, day)
    return square_off, expire


def test_letting_it_expire_used_to_cost_twice_as_much():
    """The trap, in the regime where it was real. Before October 2024 the
    exercise rate was 0.125% against 0.0625% on premium — double. A backtest
    over the older half of the lake that ignores this overstates the profit of
    anything that held to expiry."""
    square_off, expire = _square_off_vs_expire(PRE_2024)

    assert expire == pytest.approx(18.75)
    assert square_off == pytest.approx(9.46875)
    assert expire / square_off == pytest.approx(1.98, abs=0.01)


def test_budget_2026_all_but_closed_the_gap():
    """Both rates are now 0.15%, so expiry is fractionally *cheaper* than
    squaring off — intrinsic is smaller than premium by the time value, and
    there is no exit brokerage.

    Recorded because the conventional advice ("never let it expire ITM")
    inverted inside our own sample, and a strategy built today should not be
    contorted to avoid a cost that no longer exists.
    """
    square_off, expire = _square_off_vs_expire(NOW_2026)

    assert expire < square_off
    assert expire / square_off == pytest.approx(0.99, abs=0.01)


def test_exercise_stt_is_zero_out_of_the_money():
    assert exercise_stt(0.0, LOT, NOW_2026) == 0.0
    assert exercise_stt(-50.0, LOT, NOW_2026) == 0.0


def test_exercise_stt_uses_the_rate_in_force():
    # 0.125% before April 2026, 0.15% after.
    assert exercise_stt(200.0, LOT, MID_2025) == pytest.approx(18.75)
    assert exercise_stt(200.0, LOT, NOW_2026) == pytest.approx(22.50)


