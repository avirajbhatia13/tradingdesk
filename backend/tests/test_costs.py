"""Charges, checked against arithmetic done by hand rather than by the module.

Every expected number in this file is worked out longhand in the test's own
comments. That is the only way a cost model is worth anything: if the expected
values were generated by running the code, the tests would pin the behaviour
without ever having established that the behaviour is right.

The case that motivated the module is `test_costs_scale_with_size`. The old flat
model charged brokerage only, so its cost was identical at 1 lot and at 10 —
which flattered every strategy exactly as it was sized up into the range where
the flattery mattered.
"""

from datetime import date

import pytest

from app.backtest.costs import (
    SCHEDULES,
    Charges,
    CostModel,
    Fill,
    exercise_stt,
    rates_for,
)

LOT = 75

# Three dates, one in each rate regime.
PRE_2024 = date(2024, 9, 30)     # STT 0.0625%, exchange 0.05%
MID_2025 = date(2025, 6, 12)     # STT 0.10%,   exchange 0.03503%
NOW_2026 = date(2026, 8, 14)     # STT 0.15%,   exchange 0.03553%


# ---------------------------------------------------------------------------
# the schedule itself
# ---------------------------------------------------------------------------

def test_schedules_are_ordered_by_effective_date():
    """`rates_for` walks the list and breaks on the first future entry, so an
    out-of-order insert would silently return the wrong regime."""
    dates = [s.effective for s in SCHEDULES]
    assert dates == sorted(dates)


@pytest.mark.parametrize("day, stt", [
    (date(2021, 8, 16), 0.000625),   # lake's first day
    (date(2024, 9, 30), 0.000625),   # last day of the old regime
    (date(2024, 10, 1), 0.001),      # Budget 2024 takes effect
    (date(2026, 3, 31), 0.001),      # last day before Budget 2026
    (date(2026, 4, 1), 0.0015),      # Budget 2026 takes effect
    (date(2026, 8, 14), 0.0015),
])
def test_rates_for_resolves_the_regime_in_force(day, stt):
    assert rates_for(day).stt_sell_premium == stt


def test_dates_before_the_first_schedule_get_the_first_schedule():
    """Deliberate: a vendor with deeper history should not make the engine
    raise. Pricing 2019 slightly wrong beats refusing to price it."""
    assert rates_for(date(2015, 1, 1)) is SCHEDULES[0]


# ---------------------------------------------------------------------------
# a short straddle, worked longhand
# ---------------------------------------------------------------------------

def test_short_straddle_entry_matches_hand_calculation():
    """SELL 1 lot each of a 100-point CE and PE on 2026-08-14.

    Sell turnover = 100 x 75 x 2                       = 15,000
      brokerage   = 20 x 2 orders                      =     40
      STT         = 15,000 x 0.0015                    =     22.50
      exchange    = 15,000 x 0.0003553                 =      5.3295
      SEBI        = 15,000 x 0.000001                  =      0.015
      stamp       = nothing bought                     =      0
      GST         = (40 + 5.3295 + 0.015) x 0.18       =      8.16201
                                                        ----------
                                                          76.00651
    """
    fills = [Fill("SELL", 100.0, LOT), Fill("SELL", 100.0, LOT)]
    charges = CostModel().charge(fills, NOW_2026)

    assert charges.brokerage == pytest.approx(40.0)
    assert charges.stt == pytest.approx(22.50)
    assert charges.exchange == pytest.approx(5.3295)
    assert charges.sebi == pytest.approx(0.015)
    assert charges.stamp == pytest.approx(0.0)
    assert charges.gst == pytest.approx(8.16201)
    assert charges.total == pytest.approx(76.00651)


def test_short_straddle_exit_matches_hand_calculation():
    """Buying the same straddle back at 60 points each.

    Buy turnover  = 60 x 75 x 2                        =  9,000
      brokerage   = 20 x 2                             =     40
      STT         = nothing sold                       =      0
      exchange    = 9,000 x 0.0003553                  =      3.1977
      SEBI        = 9,000 x 0.000001                   =      0.009
      stamp       = 9,000 x 0.00003                    =      0.27
      GST         = (40 + 3.1977 + 0.009) x 0.18       =      7.777206
                                                        ----------
                                                          51.253906
    """
    fills = [Fill("BUY", 60.0, LOT), Fill("BUY", 60.0, LOT)]
    charges = CostModel().charge(fills, NOW_2026)

    assert charges.stt == pytest.approx(0.0)
    assert charges.stamp == pytest.approx(0.27)
    assert charges.total == pytest.approx(51.253906)


def test_round_trip_is_the_sum_of_both_sides():
    entry = [Fill("SELL", 100.0, LOT), Fill("SELL", 100.0, LOT)]
    exit_ = [Fill("BUY", 60.0, LOT), Fill("BUY", 60.0, LOT)]

    total = CostModel().round_trip(entry, exit_, NOW_2026)

    # 76.00651 + 51.253906
    assert total.total == pytest.approx(127.260416)
    # The old flat model charged 20 x 2 legs x 2 sides = 80 for this trade.
    assert total.total > 80.0


# ---------------------------------------------------------------------------
# the property the flat model got wrong
# ---------------------------------------------------------------------------

def test_costs_scale_with_size():
    """Ten lots is not ten times one lot — brokerage is flat, the rest scales.

    This is the whole reason the module exists. The old model returned 80 for
    both of these.
    """
    def straddle(lots: int) -> Charges:
        quantity = lots * LOT
        return CostModel().round_trip(
            [Fill("SELL", 100.0, quantity), Fill("SELL", 100.0, quantity)],
            [Fill("BUY", 60.0, quantity), Fill("BUY", 60.0, quantity)],
            NOW_2026,
        )

    one, ten = straddle(1), straddle(10)

    # Brokerage is per order, so it does not move at all.
    assert ten.brokerage == pytest.approx(one.brokerage)
    # STT is purely proportional, so it moves exactly ten-fold.
    assert ten.stt == pytest.approx(one.stt * 10)
    # The total lands above 400 against the flat model's unchanging 80.
    assert ten.total == pytest.approx(423.00416)


def test_charges_add_componentwise():
    a = Charges(brokerage=40.0, stt=22.5, gst=8.0)
    b = Charges(brokerage=40.0, stamp=0.27, gst=7.5)
    combined = a + b

    assert combined.brokerage == pytest.approx(80.0)
    assert combined.stt == pytest.approx(22.5)
    assert combined.stamp == pytest.approx(0.27)
    assert combined.gst == pytest.approx(15.5)


def test_charges_sum_from_empty_start():
    """`sum(charges, Charges())` is how the engine totals a run's trades."""
    items = [Charges(stt=1.0), Charges(stt=2.0), Charges(stt=4.0)]
    assert sum(items, Charges()).stt == pytest.approx(7.0)


