# rate changes inside the lake's range
# ---------------------------------------------------------------------------

def test_the_same_trade_costs_different_amounts_in_different_regimes():
    """A backtest spanning 2021-2026 crosses two rate changes. Pricing every
    trade at today's rates would overstate the cost of the older half."""
    fills = [Fill("SELL", 100.0, LOT), Fill("SELL", 100.0, LOT)]
    model = CostModel()

    old = model.charge(fills, PRE_2024)
    mid = model.charge(fills, MID_2025)
    new = model.charge(fills, NOW_2026)

    assert old.stt < mid.stt < new.stt
    # 15,000 x 0.000625 = 9.375
    assert old.stt == pytest.approx(9.375)
    # 15,000 x 0.001 = 15.0
    assert mid.stt == pytest.approx(15.0)
    # 15,000 x 0.0015 = 22.5
    assert new.stt == pytest.approx(22.5)


def test_exchange_charge_fell_when_stt_rose_in_october_2024():
    """The two October 2024 changes pushed in opposite directions — SEBI's
    uniform charge cut the exchange fee from 0.05% to 0.03503% in the same week
    STT went up. A model with only one of them gets the sign of the change
    wrong."""
    fills = [Fill("SELL", 100.0, LOT)]
    model = CostModel()

    assert model.charge(fills, PRE_2024).exchange > \
        model.charge(fills, MID_2025).exchange


