def test_stt_falls_only_on_the_sell_side():
    model = CostModel()
    sold = model.charge([Fill("SELL", 100.0, LOT)], NOW_2026)
    bought = model.charge([Fill("BUY", 100.0, LOT)], NOW_2026)

    assert sold.stt > 0
    assert bought.stt == pytest.approx(0.0)


def test_stamp_duty_falls_only_on_the_buy_side():
    model = CostModel()
    sold = model.charge([Fill("SELL", 100.0, LOT)], NOW_2026)
    bought = model.charge([Fill("BUY", 100.0, LOT)], NOW_2026)

    assert sold.stamp == pytest.approx(0.0)
    assert bought.stamp > 0


def test_exchange_and_sebi_fall_on_both_sides():
    model = CostModel()
    sold = model.charge([Fill("SELL", 100.0, LOT)], NOW_2026)
    bought = model.charge([Fill("BUY", 100.0, LOT)], NOW_2026)

    assert sold.exchange == pytest.approx(bought.exchange)
    assert sold.sebi == pytest.approx(bought.sebi)


def test_gst_excludes_stt_and_stamp_duty():
    """GST is on brokerage + exchange + SEBI only. Charging it on STT would
    inflate a seller's costs by roughly 18% of the largest line."""
    charges = CostModel().charge([Fill("SELL", 100.0, LOT)], NOW_2026)
    expected = (charges.brokerage + charges.exchange + charges.sebi) * 0.18

    assert charges.gst == pytest.approx(expected)
    assert charges.gst < charges.stt * 0.18 + expected


def test_a_credit_basket_still_pays_stamp_duty_on_its_long_leg():
    """A short strangle with a protective wing nets to a credit, but the wing
    was bought, and stamp duty does not care about the net."""
    charges = CostModel().charge(
        [Fill("SELL", 100.0, LOT), Fill("BUY", 20.0, LOT)], NOW_2026)

    assert charges.stamp == pytest.approx(20.0 * LOT * 0.00003)
    assert charges.stt == pytest.approx(100.0 * LOT * 0.0015)


