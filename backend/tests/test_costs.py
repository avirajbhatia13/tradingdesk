def test_brokerage_can_be_switched_off_to_isolate_statutory_cost():
    """"Is the edge bigger than the tax" is a different question from "is it
    bigger than the tax plus this particular broker"."""
    fills = [Fill("SELL", 100.0, LOT)]
    statutory = CostModel(charge_brokerage=False).charge(fills, NOW_2026)

    assert statutory.brokerage == 0.0
    assert statutory.stt > 0
    # GST follows brokerage down, since it is levied on it.
    assert statutory.gst == pytest.approx(
        (statutory.exchange + statutory.sebi) * 0.18)


def test_no_fills_costs_nothing():
    assert CostModel().charge([], NOW_2026).total == 0.0
